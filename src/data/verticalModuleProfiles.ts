export const domainModuleSeeds = (verticalId: DomainVerticalId, moduleId: string): DomainSeed[] => {
  const moduleProfile = getDomainModuleProfile(verticalId, moduleId);
  if (!moduleProfile) return [];
  return moduleProfile.records.map((item) => ({
    family: moduleProfile.family,
    subject: item.subject,
    segment: item.segment,
    owner: item.owner ?? moduleProfile.owner,
    impact: item.impact,
    action: item.action,
  }));
};
