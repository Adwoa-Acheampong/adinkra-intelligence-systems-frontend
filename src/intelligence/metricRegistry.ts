const formatContribution = (seed: MetricSeed, value: number) => {
  if (seed.unit === 'USD') return `USD ${Math.round(value).toLocaleString('en-US')}`;
  if (seed.unit === 'percent') return `${value.toFixed(1)} weighted points`;
  if (seed.unit === 'hours') return `${value.toFixed(1)} hr contribution`;
  if (seed.unit === 'days') return `${value.toFixed(1)} day contribution`;
  if (seed.unit === 'ratio') return `${value.toFixed(2)}× weighted`;
  return `${Math.round(value).toLocaleString('en-US')} ${seed.unit}`;
};

