export const METRIC_REGISTRY: RegisteredMetric[] = metricSeeds.map((seed) => ({
  definition: buildDefinition(seed),
  observation: buildObservation(seed),
}));

export const getRegisteredMetric = (metricId: string | null | undefined) =>
  METRIC_REGISTRY.find((metric) => metric.definition.id === metricId) ?? METRIC_REGISTRY[0];

export const getMetricsByDomain = (domain?: MetricDomain | 'all') =>
  !domain || domain === 'all'
    ? METRIC_REGISTRY
    : METRIC_REGISTRY.filter((metric) => metric.definition.domain === domain);
